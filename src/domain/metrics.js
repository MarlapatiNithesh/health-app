export const CUMULATIVE_METRICS = new Set([
  'steps', 'sleep', 'workout', 'calories', 'active_energy_burned', 'distance', 'hydration', 'active_minutes',
]);

export const METRIC_ALIASES = {
  step_count: 'steps',
  heart_rate_variability: 'hrv',
  heart_rate_variability_sdnn: 'hrv',
  heart_rate_variability_rmssd: 'hrv',
  sdnn: 'hrv',
  rmssd: 'hrv',
  oxygen_saturation: 'spo2',
  skin_temperature: 'temperature',
  body_temperature: 'temperature',
  distance_meters: 'distance',
  active_energy: 'active_energy_burned',
  basal_energy: 'basal_metabolic_rate',
  energy: 'calories',
};

export function getCanonicalMetric(metric) {
  if (!metric || typeof metric !== 'string') return '';
  const lower = metric.trim().toLowerCase();
  return METRIC_ALIASES[lower] || lower;
}

export function getMetricDefinition(metric) {
  if (!metric || typeof metric !== 'string') return null;
  const canonical = getCanonicalMetric(metric);
  return METRIC_DEFINITIONS[canonical] || METRIC_DEFINITIONS[metric.toLowerCase()] || null;
}

export function getDefaultAggregation(metric) {
  const def = getMetricDefinition(metric);
  return def ? def.defaultAggregation : 'instant';
}
